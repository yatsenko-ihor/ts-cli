// Package verification checks the requirements-to-tests traceability of the
// safety/security-critical files (see docs/do178c/README.md).
package verification

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

var (
	defRe    = regexp.MustCompile(`(?m)^- \*\*(REQ-[A-Z]+-\d{3})\*\*`)
	idRe     = regexp.MustCompile(`REQ-[A-Z]+-\d{3}`)
	verifyRe = regexp.MustCompile(`(?m)^\s*//\s*Verifies:\s*(.+)$`)
	funcRe   = regexp.MustCompile(`(?m)^func (Test\w+)\(`)
)

type requirement struct{ id, file string }

func repoRoot(t *testing.T) string {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	return filepath.Dir(wd) // tests run in <root>/verification
}

func loadRequirements(t *testing.T, root string) []requirement {
	t.Helper()
	files, err := filepath.Glob(filepath.Join(root, "verification", "requirements", "*.md"))
	if err != nil || len(files) == 0 {
		t.Fatalf("no requirement files found (%v)", err)
	}
	var reqs []requirement
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			t.Fatal(err)
		}
		for _, m := range defRe.FindAllStringSubmatch(string(data), -1) {
			reqs = append(reqs, requirement{id: m[1], file: filepath.Base(f)})
		}
	}
	return reqs
}

// loadVerifications maps requirement ID -> "pkg.TestName" entries, taking the
// Test function that follows each "Verifies:" comment.
func loadVerifications(t *testing.T, root string) map[string][]string {
	t.Helper()
	out := map[string][]string{}
	err := filepath.WalkDir(root, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && (d.Name() == ".git") {
			return filepath.SkipDir
		}
		if d.IsDir() || !strings.HasSuffix(path, "_test.go") {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		src := string(data)
		rel, _ := filepath.Rel(root, path)
		for _, loc := range verifyRe.FindAllStringSubmatchIndex(src, -1) {
			ids := idRe.FindAllString(src[loc[2]:loc[3]], -1)
			fn := "(no test function follows)"
			if m := funcRe.FindStringSubmatch(src[loc[1]:]); m != nil {
				fn = m[1]
			}
			for _, id := range ids {
				out[id] = append(out[id], fmt.Sprintf("%s: %s", rel, fn))
			}
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	return out
}

// Verifies: REQ-TRC-001, REQ-TRC-002, REQ-TRC-003
func TestEveryRequirementHasATestAndEveryTestCitesARequirement(t *testing.T) {
	root := repoRoot(t)
	reqs := loadRequirements(t, root)
	verified := loadVerifications(t, root)

	seen := map[string]string{}
	for _, r := range reqs {
		if prev, dup := seen[r.id]; dup {
			t.Errorf("%s is defined twice (%s and %s)", r.id, prev, r.file)
		}
		seen[r.id] = r.file
	}
	for _, r := range reqs {
		if len(verified[r.id]) == 0 {
			t.Errorf("%s (%s) has no test: add `// Verifies: %s` above a Test function", r.id, r.file, r.id)
		}
	}
	for id, tests := range verified {
		if _, ok := seen[id]; !ok {
			t.Errorf("%v cite unknown requirement %s", tests, id)
		}
		for _, tn := range tests {
			if strings.Contains(tn, "no test function follows") {
				t.Errorf("%s: a Verifies comment for %s is not followed by a Test function", tn, id)
			}
		}
	}
}

// UPDATE_TRACE=1 go test ./verification rewrites the traceability matrix.
func TestTraceabilityMatrixIsCurrent(t *testing.T) {
	root := repoRoot(t)
	reqs := loadRequirements(t, root)
	verified := loadVerifications(t, root)

	sort.Slice(reqs, func(i, j int) bool { return reqs[i].id < reqs[j].id })
	var b strings.Builder
	b.WriteString("# Traceability matrix\n\nGenerated by `UPDATE_TRACE=1 go test ./verification`. Do not edit.\n\n")
	b.WriteString("| Requirement | Defined in | Verified by |\n|---|---|---|\n")
	for _, r := range reqs {
		tests := append([]string(nil), verified[r.id]...)
		sort.Strings(tests)
		fmt.Fprintf(&b, "| %s | %s | %s |\n", r.id, r.file, strings.Join(tests, "<br>"))
	}
	path := filepath.Join(root, "docs", "do178c", "traceability.md")
	if os.Getenv("UPDATE_TRACE") != "" {
		if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	have, err := os.ReadFile(path)
	if err != nil || string(have) != b.String() {
		t.Fatalf("docs/do178c/traceability.md is stale: run `UPDATE_TRACE=1 go test ./verification`")
	}
}
