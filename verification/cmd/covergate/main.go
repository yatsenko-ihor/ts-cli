// Command covergate runs the test suite with a coverage profile and fails
// when the statement coverage of a gated file is below its threshold.
//
//	go run ./verification/cmd/covergate [-targets verification/coverage-targets.txt] [-report docs/do178c/coverage.md]
//
// Each line of the targets file is "<repo-relative file> <minimum percent>";
// '#' starts a comment.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"sort"
	"strconv"
	"strings"
)

const modulePath = "github.com/yatsenko-ihor/ts-cli/"

type target struct {
	file string
	min  float64
}

type counts struct{ total, covered int }

func main() {
	targetsPath := flag.String("targets", "verification/coverage-targets.txt", "file with 'path min%' lines")
	report := flag.String("report", "", "write a markdown report here")
	profile := flag.String("profile", "", "use an existing coverage profile instead of running the tests")
	flag.Parse()

	targets, err := readTargets(*targetsPath)
	if err != nil {
		fatal(err)
	}

	prof := *profile
	if prof == "" {
		f, err := os.CreateTemp("", "cover-*.out")
		if err != nil {
			fatal(err)
		}
		f.Close()
		defer os.Remove(f.Name())
		prof = f.Name()
		cmd := exec.Command("go", "test", "-coverprofile="+prof, "./...")
		cmd.Stdout, cmd.Stderr = os.Stderr, os.Stderr
		if err := cmd.Run(); err != nil {
			fatal(fmt.Errorf("tests failed: %w", err))
		}
	}

	byFile, err := readProfile(prof)
	if err != nil {
		fatal(err)
	}

	var md strings.Builder
	md.WriteString("# Statement coverage of the gated files\n\nGenerated by `go run ./verification/cmd/covergate -report docs/do178c/coverage.md`.\n\n")
	md.WriteString("| File | Statements | Covered | Coverage | Required |\n|---|---|---|---|---|\n")
	failed := false
	for _, t := range targets {
		c, ok := byFile[t.file]
		pct := 0.0
		if ok && c.total > 0 {
			pct = 100 * float64(c.covered) / float64(c.total)
		}
		status := "ok"
		if !ok || pct+1e-9 < t.min {
			status = "BELOW"
			failed = true
		}
		fmt.Printf("%-28s %6.1f%% (min %.1f%%) %s\n", t.file, pct, t.min, status)
		fmt.Fprintf(&md, "| %s | %d | %d | %.1f%% | %.1f%% |\n", t.file, c.total, c.covered, pct, t.min)
	}
	if *report != "" {
		if err := os.WriteFile(*report, []byte(md.String()), 0o644); err != nil {
			fatal(err)
		}
	}
	if failed {
		fmt.Fprintln(os.Stderr, "coverage gate FAILED")
		os.Exit(1)
	}
}

func readTargets(path string) ([]target, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []target
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if i := strings.Index(line, "#"); i >= 0 {
			line = strings.TrimSpace(line[:i])
		}
		if line == "" {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			return nil, fmt.Errorf("bad targets line %q", line)
		}
		min, err := strconv.ParseFloat(fields[1], 64)
		if err != nil {
			return nil, fmt.Errorf("bad percentage in %q: %w", line, err)
		}
		out = append(out, target{file: fields[0], min: min})
	}
	sort.Slice(out, func(i, j int) bool { return out[i].file < out[j].file })
	return out, sc.Err()
}

// readProfile sums statements per file from a Go coverage profile
// ("file:l.c,l.c numStmt count").
func readProfile(path string) (map[string]counts, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	out := map[string]counts{}
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "mode:") {
			continue
		}
		colon := strings.LastIndex(line, ":")
		if colon < 0 {
			continue
		}
		file := strings.TrimPrefix(line[:colon], modulePath)
		fields := strings.Fields(line[colon+1:])
		if len(fields) != 3 {
			continue
		}
		n, err1 := strconv.Atoi(fields[1])
		hits, err2 := strconv.Atoi(fields[2])
		if err1 != nil || err2 != nil {
			continue
		}
		c := out[file]
		c.total += n
		if hits > 0 {
			c.covered += n
		}
		out[file] = c
	}
	return out, sc.Err()
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "covergate:", err)
	os.Exit(2)
}
