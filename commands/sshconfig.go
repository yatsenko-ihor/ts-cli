// sshConfigFileName is the file `ssh-config --write` creates in the config
// directory; ~/.ssh/config only includes it.
const sshConfigFileName = "ssh_config"

// aliasOf returns the short, ssh-safe alias of a machine: the first label of
// its MagicDNS name, reduced to letters, digits, dots, hyphens and
// underscores. It is empty when nothing usable is left.
func aliasOf(d client.Device) string {
	name := d.Name
	if name == "" {
		name = d.Hostname
	}
	name = strings.TrimSuffix(name, ".")
	if strings.HasSuffix(name, ".ts.net") {
		name = strings.Split(name, ".")[0]
	}
	var b strings.Builder
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9', r == '.', r == '-', r == '_':
			b.WriteRune(r)
		default:
			b.WriteRune('-')
		}
	}
	return strings.Trim(b.String(), "-.")
}

// uniqueAlias makes alias unique among used: first with the account name,
// then with a counter.
func uniqueAlias(alias, account string, used map[string]bool) string {
	candidate := alias
	if used[candidate] && account != "" {
		candidate = alias + "-" + aliasOf(client.Device{Name: account})
	}
	base := candidate
	for n := 2; used[candidate]; n++ {
		candidate = fmt.Sprintf("%s-%d", base, n)
	}
	used[candidate] = true
	return candidate
}

// sshUserFor picks the login name for d: the one saved for the machine, the
// override, the default username. Values that are not valid usernames are
// dropped, since they end up in a config file.
func sshUserFor(d client.Device, cfg *config.Config, override string) string {
	key := d.ID
	if key == "" {
		key = d.Hostname
	}
	for _, u := range []string{cfg.MachineCredentials[key].Username, override, cfg.SSHUsername} {
		if u != "" && util.ValidateSSHUsername(u) == nil {
			return u
		}
	}
	return ""
}

// buildSSHConfig renders one Host block per machine. Passwords are never
// written, only the host name, address and login.
func buildSSHConfig(devices []client.Device, cfg *config.Config, override string) string {
	var b strings.Builder
	b.WriteString("# Generated by ts-cli ssh-config. Run it again to refresh; edits here are overwritten.\n")
	used := map[string]bool{}
	for _, d := range devices {
		alias := aliasOf(d)
		if alias == "" || len(d.Addresses) == 0 || net.ParseIP(d.Addresses[0]) == nil {
			continue
		}
		alias = uniqueAlias(alias, d.AccountName, used)
		b.WriteString("\nHost " + alias + "\n")
		b.WriteString("    HostName " + d.Addresses[0] + "\n")
		if user := sshUserFor(d, cfg, override); user != "" {
			b.WriteString("    User " + user + "\n")
		}
	}
	return b.String()
}

// writeFileAtomic writes data to path with mode 0600: it writes a sibling
// file first and renames it over path, so a reader never sees half a file.
func writeFileAtomic(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return err
	}
	if err := os.Rename(tmp, path); err != nil {
		os.Remove(tmp)
		return err
	}
	return nil
}

// ensureInclude makes sure the ssh client config at sshConfig starts with an
// Include of includePath (it has to come first: after a Host line it would
// only apply to that host). It reports whether it changed the file.
func ensureInclude(sshConfig, includePath string) (bool, error) {
	line := fmt.Sprintf("Include %q", includePath)
	old, err := os.ReadFile(sshConfig)
	if err != nil && !os.IsNotExist(err) {
		return false, err
	}
	for _, l := range strings.Split(string(old), "\n") {
		if strings.TrimSpace(l) == line {
			return false, nil
		}
	}
	return true, writeFileAtomic(sshConfig, []byte(line+"\n\n"+string(old)))
}

// NewSSHConfigCommand creates the ssh-config command.
func NewSSHConfigCommand() *cobra.Command {
	var f deviceFilter
	var user string
	var write, install bool

	cmd := &cobra.Command{
		Use:   "ssh-config",
		Short: "Print or write ~/.ssh/config entries for your machines",
		Long: `Print a Host block for every machine so that ssh, scp, rsync, git and editors
(VS Code Remote) reach it by its short name over the Tailscale address.

  --write    save the blocks in ~/.ts-cli/ssh_config (mode 0600)
  --install  as --write, and add 'Include <that file>' at the top of ~/.ssh/config

The login of a machine is the one saved for it in ts-cli, else --user, else
the default username. Passwords are never written.`,
		Example: `  ts-cli ssh-config
  ts-cli ssh-config --online --tag tag:server
  ts-cli ssh-config --install`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, args []string) error {
			if user != "" {
				if err := util.ValidateSSHUsername(user); err != nil {
					return fmt.Errorf("invalid --user: %w", err)
				}
			}
			cfg, err := config.Load()
			if err != nil {
				return fmt.Errorf("failed to load configuration: %w", err)
			}
			devices, err := listDevicesFn("", "", true)
			if err != nil {
				return err
			}
			text := buildSSHConfig(filterDevices(devices, f, time.Now()), cfg, user)
			out := cmd.OutOrStdout()
			if !write && !install {
				fmt.Fprint(out, text)
				return nil
			}

			// config.Load succeeded, so the directory is known and valid.
			dir, _ := util.ConfigDir()
			target := filepath.Join(dir, sshConfigFileName)
			if err := writeFileAtomic(target, []byte(text)); err != nil {
				return fmt.Errorf("failed to write %s: %w", target, err)
			}
			fmt.Fprintf(out, "Wrote %s\n", target)
			if !install {
				fmt.Fprintf(out, "Add this line at the top of ~/.ssh/config (or run with --install):\n  Include %q\n", target)
				return nil
			}
			home, err := os.UserHomeDir()
			if err != nil {
				return fmt.Errorf("failed to find the home directory: %w", err)
			}
			changed, err := ensureInclude(filepath.Join(home, ".ssh", "config"), target)
			if err != nil {
				return fmt.Errorf("failed to update ~/.ssh/config: %w", err)
			}
			if changed {
				fmt.Fprintln(out, "Added the Include line to ~/.ssh/config")
			} else {
				fmt.Fprintln(out, "~/.ssh/config already includes it")
			}
			return nil
		},
	}
	cmd.Flags().BoolVar(&f.Online, "online", false, "Only online devices")
	cmd.Flags().StringVar(&f.OS, "os", "", "Only devices with this OS (case-insensitive)")
	cmd.Flags().StringArrayVar(&f.Tags, "tag", nil, "Only devices with this tag (repeatable, all must match)")
	cmd.Flags().StringArrayVar(&f.Accounts, "account", nil, "Only devices of this account (repeatable, any of)")
	cmd.Flags().StringVar(&f.Name, "name", "", "Only devices whose name or hostname contains this text")
	cmd.Flags().StringVar(&user, "user", "", "Login for machines without a saved one")
	cmd.Flags().BoolVar(&write, "write", false, "Write ~/.ts-cli/ssh_config instead of printing")
	cmd.Flags().BoolVar(&install, "install", false, "Write the file and add an Include line to ~/.ssh/config")
	return cmd
}
